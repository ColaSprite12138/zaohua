import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

const tablesDir = fileURLToPath(new URL('../tables/', import.meta.url));
const generatedDir = fileURLToPath(new URL('../generated/', import.meta.url));
const TABLE_NAME = /^[a-z][a-z0-9_]*\.xlsx$/;

describe('resource table contract', () => {
  it('has a tables directory with the authoring README', () => {
    expect(existsSync(tablesDir)).toBe(true);
    expect(existsSync(`${tablesDir}README.md`)).toBe(true);
  });

  it('accepts only lowercase snake_case .xlsx source tables', () => {
    const files = readdirSync(tablesDir).filter((f) => f !== 'README.md');
    expect(files.every((f) => TABLE_NAME.test(f))).toBe(true);
    expect(new Set(files).size).toBe(files.length);
  });

  it('ships exactly one generated .ts per source table, no orphans', () => {
    expect(existsSync(generatedDir)).toBe(true);
    const sources = new Set(
      readdirSync(tablesDir).filter((f) => f.endsWith('.xlsx')).map((f) => f.replace(/\.xlsx$/, '')),
    );
    const outputs = new Set(
      readdirSync(generatedDir).filter((f) => f.endsWith('.ts')).map((f) => f.replace(/\.ts$/, '')),
    );
    expect([...outputs].sort()).toEqual([...sources].sort());
  });

  it('generated files carry their source SHA-256 and never hand-edit marker', () => {
    for (const out of readdirSync(generatedDir).filter((f) => f.endsWith('.ts'))) {
      const text = readFileSync(`${generatedDir}${out}`, 'utf8');
      expect(text).toMatch(/GENERATED by scripts\/export_tables\.py - DO NOT EDIT/);
      expect(text).toMatch(/^ \* sha256: [0-9a-f]{64}$/m);
    }
  });

  it('item / monster_loot / loot_pool data survive the conversion', async () => {
    const { item } = await import('../generated/item.ts');
    const { monster_loot } = await import('../generated/monster_loot.ts');
    const { loot_pool } = await import('../generated/loot_pool.ts');
    expect(item).toHaveLength(12);
    expect(monster_loot).toHaveLength(2);
    expect(loot_pool).toHaveLength(12);
    expect(new Set(item.map((r) => r.id)).size).toBe(12);
    // Weight ladder 10/8/6/4/2/1 in both pools = 31 each.
    for (const poolId of [1, 2]) {
      const rows = loot_pool.filter((r) => r.loot_pool_id === poolId);
      expect(rows.map((r) => r.weight)).toEqual([10, 8, 6, 4, 2, 1]);
      expect(rows.reduce((n, r) => n + r.weight, 0)).toBe(31);
    }
    // Every loot item id resolves to a real item row.
    const ids = new Set(item.map((r) => r.id));
    for (const row of loot_pool) expect(ids.has(row.item_id)).toBe(true);
  });
});
