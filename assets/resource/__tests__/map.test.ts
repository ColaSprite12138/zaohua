import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

const mapsDir = fileURLToPath(new URL('../maps/', import.meta.url));
const sourceBytes = readFileSync(`${mapsDir}arena.ldtk`);
const generatedText = readFileSync(`${mapsDir}arena.generated.ts`, 'utf8');
const project = JSON.parse(sourceBytes.toString('utf8')) as {
  jsonVersion: string;
  externalLevels: boolean;
  defaultGridSize: number;
  levels: { pxWid: number; pxHei: number }[];
};

const WALKABLE = new Set(['0', '2']);

async function loadMap() {
  return (await import('../maps/arena.generated.ts')).arena;
}

function walkableFromSpawn(arena: Awaited<ReturnType<typeof loadMap>>): Set<string> {
  const key = (c: number, r: number) => `${c},${r}`;
  const seen = new Set<string>([key(arena.spawn.col, arena.spawn.row)]);
  const queue: [number, number][] = [[arena.spawn.col, arena.spawn.row]];
  while (queue.length > 0) {
    const [c, r] = queue.shift()!;
    for (const [dc, dr] of [[1, 0], [-1, 0], [0, 1], [0, -1]] as const) {
      const nc = c + dc;
      const nr = r + dr;
      if (nc < 0 || nc >= arena.cols || nr < 0 || nr >= arena.rows) continue;
      const k = key(nc, nr);
      if (seen.has(k) || !WALKABLE.has(arena.terrain[nr]![nc]!)) continue;
      seen.add(k);
      queue.push([nc, nr]);
    }
  }
  return seen;
}

describe('LDtk arena map contract', () => {
  it('ships an LDtk 1.5.x project with embedded level data and one level', () => {
    expect(project.jsonVersion).toMatch(/^1\.5\./);
    expect(project.externalLevels).toBe(false);
    expect(project.levels).toHaveLength(1);
  });

  it('generated map carries the no-hand-edit marker and the live source SHA-256', () => {
    const digest = createHash('sha256').update(sourceBytes).digest('hex');
    expect(generatedText).toMatch(/GENERATED by scripts\/import_map\.py - DO NOT EDIT/);
    expect(generatedText).toMatch(new RegExp(`^ \\* sha256: ${digest}$`, 'm'));
  });

  it('terrain dimensions, tile alphabet and world size match the LDtk level', async () => {
    const arena = await loadMap();
    expect(arena.terrain).toHaveLength(arena.rows);
    for (const row of arena.terrain) {
      expect(row).toHaveLength(arena.cols);
      expect(/^[0-3]+$/.test(row)).toBe(true);
    }
    expect(arena.gridSize).toBe(project.defaultGridSize);
    expect(arena.pxWid).toBe(arena.cols * arena.gridSize);
    expect(arena.pxHei).toBe(arena.rows * arena.gridSize);
    expect(arena.pxWid).toBe(project.levels[0]!.pxWid);
    expect(arena.pxHei).toBe(project.levels[0]!.pxHei);
    // Bigger than the 1280x720 viewport: this map needs a camera.
    expect(arena.pxWid).toBeGreaterThan(1280);
    expect(arena.pxHei).toBeGreaterThan(720);
  });

  it('spawn and every monster sit on walkable, reachable terrain', async () => {
    const arena = await loadMap();
    const seen = walkableFromSpawn(arena);
    expect(WALKABLE.has(arena.terrain[arena.spawn.row]![arena.spawn.col]!)).toBe(true);
    expect(seen.has(`${arena.spawn.col},${arena.spawn.row}`)).toBe(true);
    expect(arena.monsters.length).toBeGreaterThan(0);
    for (const m of arena.monsters) {
      expect(WALKABLE.has(arena.terrain[m.row]![m.col]!)).toBe(true);
      expect(seen.has(`${m.col},${m.row}`)).toBe(true);
    }
    expect(new Set(arena.monsters.map((m) => m.id)).size).toBe(arena.monsters.length);
  });

  it('every monsterId resolves to a row in monster_loot.xlsx', async () => {
    const arena = await loadMap();
    const { monster_loot } = await import('../generated/monster_loot.ts');
    const ids = new Set(monster_loot.map((row) => row.id));
    for (const m of arena.monsters) expect(ids.has(m.monsterId)).toBe(true);
  });

  it('entity pixel coordinates are the centre of their grid cell', async () => {
    const arena = await loadMap();
    const half = arena.gridSize / 2;
    expect(arena.spawn.x).toBe(arena.spawn.col * arena.gridSize + half);
    expect(arena.spawn.y).toBe(arena.spawn.row * arena.gridSize + half);
    for (const m of arena.monsters) {
      expect(m.x).toBe(m.col * arena.gridSize + half);
      expect(m.y).toBe(m.row * arena.gridSize + half);
    }
  });
});
