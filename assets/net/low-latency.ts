/**
 * 联机低延迟临时开关（2026-11-23 用户要求）。
 *
 * ## 用户口径
 * 「收到 2800 就执行 2800，但前提是 2799 已经收到并执行；2799 的前提是 2798
 * 已经收到并执行。没收到 2799 就向服务器补这一帧。」—— **去掉排队缓冲，不去掉有序性**。
 *
 * ## 只改了什么
 * **只有 `lookahead`：2 → 1。** `canStep()` 从「手里要排够 2 帧」变成「只要
 * `nextTick` 这一帧到了」，于是省掉 24 Hz 下 83 ms 播放缓冲里的一帧（42 ms）。
 * 角标「领先」从稳定 3 降到 0~1。
 *
 * ## 刻意**没**改什么（2026-11-23 修正，重要）
 * 执行仍然走原来的**墙钟节拍**：`addTime` → `takeStep`（`acc >= dt` 才走一步）。
 * 上一版曾顺手把这一步也绕开，改成「收到帧就立刻执行」，结果当天用户实测
 * 「移动时整个相机抽搐」。原因：
 *
 * - `paintWithInterp` 连**相机**一起做「渲染落后逻辑一步」插值，
 *   `paint()` 又用 `Math.round(s.camera.x)` 整数平移整幅画面；
 * - 那种插值要求执行恰好发生在 `alpha` 走到 1 的那一刻（墙钟节拍保证），
 *   执行前后画面才无缝：alpha=1 画 cur，执行后 alpha=0 画「新 prev = 旧 cur」；
 * - 改成收包驱动后，执行落在 alpha=0.2 / 0.9 的任意时刻，每次执行画面突跳
 *   `(1-alpha)` 个逻辑步，而收包间隔带网络抖动 → 跳幅忽大忽小 = 相机抽搐。
 *
 * **2026-11-23 补充**：玩家与相机已换成 `assets/game/visual-motion.ts` 的渲染层
 * 追随器，`alpha` 只再用于怪的插值，所以「必须落在 alpha=1」不再是硬约束。
 * 但**节拍照旧不动**：收包即执行会让一帧内的 `S`（画面到逻辑目标的距离）突增，
 * 追随器只能用 `1.3V` 慢慢追，反而持续落后；按 `dt` 稳定执行才能让稳态 `S`
 * 恒定在一个逻辑步。也就是说这条历史结论换了理由，结论没变 —— 别去动节拍。
 *
 * 所以「去缓冲」和「去墙钟节拍」是两件事，**只需要前者**。保留节拍的代价
 * 是帧到了最多再等一个 dt（平均 21 ms），远小于省下的 42 ms，且画面平滑。
 *
 * ## 没删的东西
 * - 不跳帧、不猜输入、不填空白：`S(t+1) = F(S(t), I_all(t))` 不变。
 * - 有洞时 `canStep()` 为 false → 一帧都不走 → `requestReplay()` 把缺的那帧
 *   要回来 → 补齐后才继续按序执行。`accept` / `canStep` / `take` / `requestReplay`
 *   一条都没删，补帧通道正是有序性的保障。
 * - 两端执行顺序、hash 对账口径、渲染插值全部原样。
 *
 * ## 怎么加回来
 * 把 `LOW_LATENCY_NET` 改回 `false` → `EFFECTIVE_LOOKAHEAD` 回到 2，
 * 旧的 2 帧缓冲与 8/3 追帧滞回自动生效。其余代码一行都不用动。
 *
 * ## 代价（临时模式，已知并接受）
 * 没有抖动缓冲，网络晚到 40 ms 会偶发顿一下（但不会持续抽搐）。本机输入
 * 仍需一个服务器回程（工程明确不做客户端预表现），这部分延迟消不掉。
 */
export const LOW_LATENCY_NET = true;

/** 原值：播放缓冲 2 帧 = 24 Hz 下 83 ms。 */
export const BUFFERED_LOOKAHEAD = 2;

/** 低延迟：手里只要有 `nextTick` 这一帧就允许执行。 */
export const IMMEDIATE_LOOKAHEAD = 1;

/** 当前生效的播放缓冲深度。改名/改值都只在这一个地方。 */
export const EFFECTIVE_LOOKAHEAD = LOW_LATENCY_NET
  ? IMMEDIATE_LOOKAHEAD
  : BUFFERED_LOOKAHEAD;

/**
 * **收包即执行**（2026-11-23 用户实验开关）。
 *
 * `true`：`advanceNet` 不再等墙钟节拍（`acc >= dt`），一收到连续帧就在**本渲染帧**
 * 里全部执行（单帧仍受 `MAX_CATCHUP_STEPS` 限制）。目的：把角标的「领先」从追帧
 * 滞回的下限 3 帧（≈125 ms）压到 0~1，降低输入与画面的延迟。
 *
 * ## 为什么现在敢改（此前明确禁止过）
 *
 * 2026-11-23 上午试过一次「收包即执行」，用户实测「相机抽搐」。当时的根因是
 * `paintWithInterp` 依赖 `alpha = 1` 的时刻 —— 执行落在任意 `alpha` 会让画面
 * 每次突跳 `(1-alpha)` 个身位。
 *
 * 现在渲染换成 `game/visual-motion.ts` 的追随器，位置**不再由 `acc` 推导**。
 * 执行时刻变化只会让 `S`（画面到逻辑目标的距离）短暂变大，追随器照常平滑抹平，
 * 所以那条禁忌的前提已经消失。
 *
 * ## 被牺牲的东西
 *
 * - `stepClock.acc` 不再驱动执行：`addTime` 停跑，`forceStep` 每步扣账后由
 *   `clearDebt` 归零 → `renderAlpha` 恒 0（只剩 `interp.ts` 的单测还在读它）；
 * - 执行节奏从「每 dt 一步」变成「每个广播批次一步」，`S` 在 0~1 步之间波动，
 *   追随器输出仍是匀速 `V`；
 * - 单帧最多 `MAX_CATCHUP_STEPS` 步，积压靠「每帧 6 步」消化（144 fps × 6 ≈ 864
 *   步/秒，是服务器产出速率的 36 倍），所以 `lead` 会很快回落到 0~1。
 *
 * ## 回滚
 *
 * 改回 `false` 即恢复墙钟节拍，其余代码一行不用动。
 */
export const IMMEDIATE_EXECUTION = true;
